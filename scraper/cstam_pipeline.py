def polite_get(url, check_robots=True, delay=(1.5, 3.0)):
    if check_robots and not is_allowed(url):
        print(f"  [skip] robots.txt disallows: {url}")
        return None
    for attempt in range(1, MAX_RETRIES + 1):
        try:
            r = _session.get(url, timeout=REQUEST_TIMEOUT)
            if r.status_code in (401, 403, 406, 429):
                print(f"  [blocked] HTTP {r.status_code}: {url}")
                if r.status_code in (403, 406):
                    print("     -> try --browser-ua, or run from a Tunisian connection")
                return None
            r.raise_for_status()
            return r
        except requests.RequestException as e:
            if attempt == MAX_RETRIES:
                print(f"  [error] giving up on {url}: {e}")
            else:
                w = 2.0 * 2 ** (attempt - 1)
                print(f"  [retry {attempt}/{MAX_RETRIES}] {e}; waiting {w:.0f}s")
                time.sleep(w)
        finally:
            time.sleep(random.uniform(*delay))
    return None


def is_allowed(url):
    if not RESPECT_ROBOTS:
        return True
    p = urlparse(url)
    if p.netloc not in _robots:
        rp = robotparser.RobotFileParser()
        r = polite_get(f"{p.scheme}://{p.netloc}/robots.txt", check_robots=False, delay=(0.5, 1.0))
        if r is None:
            rp.allow_all = True
        else:
            try:
                rp.parse(r.text.splitlines())
            except Exception:
                rp.allow_all = True
        _robots[p.netloc] = rp
    return _robots[p.netloc].can_fetch(_session.headers["User-Agent"], url)


