DETAIL_RE = re.compile(r"^/appels-offres/([a-z0-9-]+)/(\d+)-([a-z0-9]+)/?$", re.I)
DATE_RE = re.compile(r"(\d{2})/(\d{2})/(\d{4})(?:\s+(\d{2}:\d{2})(?::\d{2})?)?")
TYPE_WORDS = ["National", "International", "Avis de report", "Avis d'infructuosité", "Avis de non attribution",
              "Avis de résultat"]


def _detail(href):
    path = urlparse(urljoin(BASE_AO, href)).path
    m = DETAIL_RE.match(path)
    return path, (m.group(2) if m else None)


def _country_from_row(cont):
    for img in cont.find_all("img"):
        src = (img.get("src") or "").lower()
        if "flag_" in src:
            label = clean(img.get("alt") or img.get("title") or "")
            if label:
                return label
            return {"tun": "Tunisie", "mar": "Maroc", "alg": "Algérie", "dza": "Algérie"}.get(
                re.search(r"flag_([a-z]+)", src).group(1), "")
    return ""


def parse_listing(page_html, slug):
    soup = BeautifulSoup(page_html, "lxml")
    anchors = {}
    for a in soup.find_all("a", href=True):
        path, tid = _detail(a["href"])
        if tid:
            anchors.setdefault(tid, []).append((a, path))
    rows = []
    for tid, lst in anchors.items():
        first_a, path = lst[0]
        cont = first_a
        while cont.parent is not None and cont.parent.name not in ("body", "html", "[document]"):
            ids = {_detail(x["href"])[1] for x in cont.parent.find_all("a", href=True)} - {None}
            if len(ids) > 1:
                break
            cont = cont.parent
        tokens = [clean(t) for t in cont.stripped_strings if clean(t)]
        flat = " ".join(tokens)
        cat_label = AO_CATEGORIES.get(slug, slug)
        for x in cont.find_all("a", href=True):
            if urlparse(urljoin(BASE_AO, x["href"])).path.rstrip("/") == f"/appels-offres/{slug}" and clean(x.get_text()):
                cat_label = clean(x.get_text())
                break
        code = clean(first_a.get_text())
        try:
            ci = tokens.index(cat_label)
        except ValueError:
            ci = next((i for i, t in enumerate(tokens) if cat_label in t), None)
        head = tokens[:ci] if ci is not None else tokens
        cand = [t for t in head if not t.isdigit() and t != code and t.lower() != "voir" and not DATE_RE.search(t)]
        title = cand[0] if cand else ""
        if ci is None and cand:
            title = max(cand, key=len)
        dates = list(DATE_RE.finditer(flat))
        pub = dl = None
        hour = ""
        if dates:
            d1 = dates[-1]
            dl = f"{d1.group(3)}-{d1.group(2)}-{d1.group(1)}"
            hour = d1.group(4) or ""
            if len(dates) >= 2:
                d0 = dates[0]
                pub = f"{d0.group(3)}-{d0.group(2)}-{d0.group(1)}"
        country = _country_from_row(cont)
        after = tokens[ci + 1:] if ci is not None else []
        ref_tokens, type_raw = [], ""
        for t in after:
            if DATE_RE.match(t) or t.lower() == "voir":
                break
            if t in TYPE_WORDS:
                type_raw = type_raw or t
            elif t != country:
                ref_tokens.append(t)
        reference = clean(" ".join(ref_tokens))
        rows.append({
            "tender_id": tid, "reference_raw": reference, "buyer_code": code if len(code) <= 3 else "",
            "objet": title, "titre_tronque": title.endswith("...") or title.endswith("…"),
            "type_commande": cat_label, "procedure": type_raw, "pays": country, "date_publication": pub,
            "date_limite": dl, "heure_limite": hour, "url": urljoin(BASE_AO, path), "source_site": "appeloffres.com"})
    return rows


def scrape_ao(max_pages, country, it_only, min_score, extra_keywords, debug_path):
    seen, kept, listed, d_country, d_it = set(), [], 0, 0, 0
    for slug in AO_CATEGORIES:
        n_pages = max_pages
        for page in range(1, max_pages + 1):
            url = f"{BASE_AO}/appels-offres/{slug}" + (f"?page={page}" if page > 1 else "")
            print(f"[appeloffres] {slug} page {page}/{n_pages}")
            r = polite_get(url, delay=(2.0, 3.5))
            if r is None:
                break
            if "/login" in r.url:
                print("[appeloffres] redirected to login: listing not public. Stopping.")
                break
            if page == 1:
                m = re.search(r"page\s*\d+\s*/\s*(\d+)", BeautifulSoup(r.text, "lxml").get_text(" "), re.I)
                if m:
                    n_pages = min(max_pages, int(m.group(1)))
            rows = parse_listing(r.text, slug)
            print(f"  parsed {len(rows)} tender rows")
            if not rows:
                with open(debug_path, "w", encoding="utf-8") as f:
                    f.write(r.text)
                print(f"  [debug] page saved to {debug_path}")
                break
            for rec in rows:
                listed += 1
                if rec["url"] in seen:
                    continue
                seen.add(rec["url"])
                if country != "all" and rec["pays"] and strip_accents(rec["pays"]) != strip_accents(country):
                    d_country += 1
                    continue
                rec["it_score"], rec["it_terms"] = it_score(rec["objet"], extra_keywords)
                if it_only and rec["it_score"] < min_score:
                    d_it += 1
                    continue
                kept.append(rec)
            if page >= n_pages:
                break
    print(f"[appeloffres] listed {listed} | other country: {d_country} | not IT: {d_it} | kept {len(kept)}")
    return kept


