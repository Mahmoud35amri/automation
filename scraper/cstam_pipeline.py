def _norm_title(s):
    s = strip_accents(ARABIC_RE.sub(" ", s or ""))
    s = re.sub(r"(\.\.\.|…)\s*$", "", s.strip())
    return " ".join(re.sub(r"[^a-z0-9 ]+", " ", s).split())


def _sim(a, b):
    a, b = _norm_title(a), _norm_title(b)
    if not a or not b:
        return 0.0
    n = min(len(a), len(b), 70)                         # titles are truncated: compare equal-length prefixes
    return SequenceMatcher(None, a[:n], b[:n]).ratio()


def link_portals(hc_rows, ao_rows, threshold=0.8):
    linked, rest = 0, []
    for a in ao_rows:
        best, bs = None, 0.0
        for h in hc_rows:
            if not a.get("date_limite") or h.get("date_limite") != a.get("date_limite"):
                continue
            s = max(_sim(a.get("objet"), h.get("objet")), _sim(a.get("objet"), h.get("descriptif")))
            if s > bs:
                best, bs = h, s
        if best is not None and bs >= threshold:
            best.setdefault("also_listed_on", []).append({"source": a.get("source_site"), "url": a.get("url"),
                                                          "match": round(bs, 2)})
            best["titre_portail_secondaire"] = a.get("objet")
            linked += 1
        else:
            rest.append(a)
    print(f"[link] {linked} appeloffres.com row(s) folded into a HAICOP record")
    return list(hc_rows) + rest


