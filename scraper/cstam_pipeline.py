def it_score(text, extra_keywords=None):
    """(score, matched_terms): strong = 2 pts, weak = 1 pt, user keyword = 2 pts."""
    t = strip_accents(ARABIC_RE.sub(" ", text or ""))
    for ph in IT_EXCLUDE:
        t = t.replace(ph, " ")
    score, hits = 0, []
    for term, rx in _STRONG:
        if rx.search(t):
            score += 2
            hits.append(term)
    for term, rx in _WEAK:
        if rx.search(t):
            score += 1
            hits.append(term)
    for kw in (extra_keywords or []):
        kw = strip_accents(kw).strip()
        if kw and _term_re(kw).search(t):
            score += 2
            hits.append(kw)
    return score, sorted(set(hits))


