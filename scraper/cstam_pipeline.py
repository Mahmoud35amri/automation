def deadline_dt(r):
    try:
        y, m, d = (int(x) for x in str(r.get("date_limite")).split("-"))
    except Exception:
        return None, False
    mm = re.match(r"\s*(\d{1,2}):(\d{2})", str(r.get("heure_limite") or ""))
    hh, mi = (int(mm.group(1)), int(mm.group(2))) if mm else (0, 0)
    known = bool(mm) and (hh, mi) != (0, 0)            # "00:00" = time not published
    if not known:
        hh, mi = 23, 59
    try:
        return datetime(y, m, d, hh, mi, tzinfo=TUNIS), known
    except ValueError:
        return None, False


def _items(text):
    text = (text or "").strip()
    if not text:
        return []
    parts = re.split(r"\n\s*(?:\d+[.)]|[-•*])\s+", "\n" + text)
    return [p for p in (re.sub(r"\s+", " ", x).strip() for x in parts) if p]


def _sentences(text):
    """Split a descriptif into one requirement per sentence / bullet."""
    out = []
    for it in _items(text):
        out += [s.strip() for s in re.split(r"(?<=[.;])\s+(?=[A-Z\u00C0-\u00DE])", it) if s.strip()]
    return out


def _req_level(line):
    l = strip_accents(line)
    if re.search(r"souhait|un plus|optionnel|facultatif", l):
        return "souhaite"
    if re.search(r"exig|obligatoire|\bdoit\b|\bdoivent\b|imperatif|\brequis", l):
        return "exige"
    return "non_precise"


def extract_requirements(r, limit=25):
    """Requirement lines for the RAG / requirements matrix. Only source text, never invented."""
    srcs = _sentences(r.get("descriptif")) + [l["objet"] for l in (r.get("lots") or []) if l.get("objet")] \
        + _items((r.get("document_sections") or {}).get("prescriptions")) \
        + _items((r.get("document_sections") or {}).get("personnel"))
    out, seen = [], set()
    for s in srcs:
        s = re.sub(r"\s+", " ", ARABIC_RE.sub(" ", s)).strip()
        k = re.sub(r"\W+", " ", strip_accents(s))
        if len(s) >= 12 and k not in seen:
            seen.add(k)
            out.append({"text": s, "level": _req_level(s)})
    return out[:limit]


