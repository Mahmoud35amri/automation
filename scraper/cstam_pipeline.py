def _harvest_ids(text, found, source=""):
    n0 = len(found)
    for tid in dict.fromkeys(TENDER_RE.findall(text or "")):
        found.setdefault(tid, {"tender_id": tid, "url": f"{BASE_HC}/fr/appels-doffres/{tid}"})
    if len(found) > n0:
        print(f"    + {len(found) - n0} tender id(s) from {source}")
    return len(found) - n0


def _listing_worker(max_pages, headless, debug_path):
    from playwright.sync_api import sync_playwright
    found, responses, done = {}, [], set()

    def harvest(page, tag):
        added = _harvest_ids(page.content(), found, f"{tag} / DOM")
        for r in responses:
            if id(r) in done:
                continue
            done.add(id(r))
            try:
                added += _harvest_ids(r.text(), found, f"{tag} / network {r.url[:70]}")
            except Exception:
                pass
        return added

    with sync_playwright() as pw:
        browser = pw.chromium.launch(headless=headless)
        ctx = browser.new_context(user_agent=BROWSER_UA, locale="fr-FR", viewport={"width": 1400, "height": 900})
        page = ctx.new_page()
        page.on("response", lambda r: responses.append(r) if (
            r.request.resource_type in ("xhr", "fetch") or "json" in r.headers.get("content-type", "")) else None)
        try:
            main = page.goto(LIST_URL, wait_until="networkidle", timeout=60000)
        except Exception as e:
            print(f"[haicop] could not load {LIST_URL}: {e}\n{_BLOCK_HINT}")
            browser.close()
            return []
        page.wait_for_timeout(2500)
        status = main.status if main else "?"
        body_txt = clean(page.inner_text("body"))
        print(f"[haicop] HTTP {status} | title={page.title()!r} | xhr/fetch seen={len(responses)}")
        if status not in (200, "?") or re.search(r"captcha|access denied|forbidden|cloudflare|blocked|robot",
                                                  body_txt[:1500], re.I):
            print(f"[haicop] page looks BLOCKED: {body_txt[:200]!r}\n{_BLOCK_HINT}")
        harvest(page, "initial load")

        if not found:                                   # results may need a click on 'Rechercher'
            for css in _SEARCH_BUTTONS:
                btn = page.query_selector(css)
                if btn and btn.is_visible():
                    try:
                        btn.click()
                        page.wait_for_load_state("networkidle", timeout=30000)
                    except Exception as e:
                        print(f"  [info] click/wait issue: {e}")
                    page.wait_for_timeout(2500)
                    if harvest(page, "after search"):
                        break
        if found:
            try:                                        # more rows per page
                sel = page.query_selector("select[name$='_length'], select[name*='length']")
                nums = [int(o.get_attribute("value")) for o in sel.query_selector_all("option")
                        if (o.get_attribute("value") or "").isdigit()] if sel else []
                if nums:
                    sel.select_option(str(max(nums)))
                    page.wait_for_load_state("networkidle")
                    page.wait_for_timeout(1500)
                    harvest(page, "page length")
            except Exception as e:
                print(f"  [info] page-length selector not usable: {e}")
            for page_no in range(2, max_pages + 1):
                nxt = next((page.query_selector(c) for c in _NEXT_BUTTONS if page.query_selector(c)), None)
                if not nxt:
                    break
                cls = (nxt.get_attribute("class") or "") + " " + (nxt.evaluate("e => e.parentElement.className") or "")
                if "disabled" in cls or nxt.get_attribute("aria-disabled") == "true":
                    break
                try:
                    nxt.click()
                    page.wait_for_load_state("networkidle", timeout=30000)
                except Exception:
                    pass
                page.wait_for_timeout(1500)
                print(f"[haicop] listing page {page_no}")
                if not harvest(page, f"page {page_no}"):
                    break
        if not found:
            with open(debug_path, "w", encoding="utf-8") as f:
                f.write(page.content())
            print(f"[haicop] NOTHING FOUND. Rendered page saved to {debug_path}")
        browser.close()
    return list(found.values())


def scrape_listing(max_pages, headless, debug_path):
    if not is_allowed(LIST_URL):
        print("[haicop] robots.txt disallows the listing page; stopping.")
        return []

    def go():
        with ThreadPoolExecutor(max_workers=1) as ex:    # avoids "sync API inside asyncio loop" in Colab
            return ex.submit(_listing_worker, max_pages, headless, debug_path).result()
    try:
        return go()
    except Exception as e:
        if "Executable doesn't exist" in str(e) or "playwright install" in str(e):
            print("[haicop] installing Chromium for Playwright (one-time)...")
            subprocess.run([sys.executable, "-m", "playwright", "install", "chromium"], check=False)
            subprocess.run([sys.executable, "-m", "playwright", "install-deps", "chromium"], check=False)
            try:
                return go()
            except Exception as e2:
                print(f"[haicop] listing failed after install: {e2}")
                return []
        print(f"[haicop] listing failed: {e}")
        return []


