def extract_sections(doc_text, max_chars=1800):
    out = {}
    if not doc_text:
        return out
    hits = sorted((m.start(), m.end(), k) for k, pat in _SECTION_HEADERS.items()
                  for m in [re.search(pat, doc_text, re.I)] if m)
    for i, (s, e, key) in enumerate(hits):
        end = hits[i + 1][0] if i + 1 < len(hits) else len(doc_text)
        body = doc_text[e:end].strip(" :\n")[:max_chars].strip()
        if body:
            out[key] = body
    return out


