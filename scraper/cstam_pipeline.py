def lead_score(r):
    """0-100 ranking for the sales dashboard: fit + IT signal + urgency + data completeness."""
    if r["expired"]:
        return 0
    s = {"high": 60, "medium": 40, "low": 20, "none": 0}[r["olivesoft_fit"]]
    s += int(min(r.get("it_score") or 0, 10) * 1.5) + r["completeness"] // 10
    if r["urgent"]:
        s += 10
    elif r["days_left"] is not None and r["days_left"] <= 14:
        s += 5
    return min(s, 100)


