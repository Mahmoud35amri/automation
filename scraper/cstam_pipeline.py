def filter_rows(rows, keep_expired, min_fit):
    kept, dropped = [], []
    for r in rows:
        if r["expired"] and not keep_expired:
            dropped.append((r, "expired"))
        elif r["fit_rank"] < FIT_RANK[min_fit]:
            dropped.append((r, f"fit<{min_fit}"))
        else:
            kept.append(r)
    return kept, dropped


def to_frame(rows):
    df = pd.DataFrame(rows) if rows else pd.DataFrame(columns=COLUMNS)
    for c in COLUMNS:
        if c not in df.columns:
            df[c] = None
    if rows:
        df["detected_at"] = datetime.now(timezone.utc).isoformat()
        df = df.drop_duplicates(subset=["url"])
        df = df.sort_values(["lead_score", "date_limite"], ascending=[False, True], na_position="last").reset_index(drop=True)
    return df[COLUMNS]


def _records(df):
    return [] if df.empty else json.loads(df.to_json(orient="records", force_ascii=False))


def export_json(df, path):
    recs = _records(df)
