def _term_re(t):
    return re.compile(r"(?<![a-z0-9])" + re.escape(t) + r"s?(?![a-z0-9])")


def _dedupe(terms):
    base = set(terms)
    return [t for t in dict.fromkeys(terms) if not (t.endswith("s") and t[:-1] in base)]


_STRONG = [(t, _term_re(t)) for t in _dedupe(IT_STRONG)]
