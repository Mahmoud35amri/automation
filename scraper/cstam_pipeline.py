_MONTHS_FR = ["janvier", "fevrier", "mars", "avril", "mai", "juin", "juillet", "aout", "septembre", "octobre",
              "novembre", "decembre"]


def _ascii(t):
    s = str(t if t is not None else "")
    s = (s.replace("«", '"').replace("»", '"').replace("“", '"').replace("”", '"').replace("–", "-")
          .replace("—", "-").replace("’", "'").replace("‘", "'").replace("…", "..."))
    s = unicodedata.normalize("NFKD", ARABIC_RE.sub(" ", s))
    s = "".join(c for c in s if not unicodedata.combining(c))
    return xml_escape(s.encode("ascii", errors="replace").decode("ascii"))


def _long_date(iso):
    try:
        y, m, d = iso.split("-")
        return f"{int(d)} {_MONTHS_FR[int(m) - 1]} {y}"
    except Exception:
        return ""


def _header_line(r):
    proc = re.sub(r"(?i)^appel d.offres?\s*", "", str(r.get("procedure") or "")).strip()
    base = {"consultation": "CONSULTATION", "manifestation_interet": "MANIFESTATION D'INTERET",
            "report": "AVIS DE REPORT"}.get(r.get("notice_kind"), "APPEL D'OFFRES")
    num, tid = r.get("numero_ao") or r.get("tender_id") or "", r.get("tender_id") or ""
    return f"{base}{(' ' + proc.upper()) if proc else ''} N {num}{f' (ID {tid})' if tid and str(num) != tid else ''}"


def export_pdf(df, path):
    """One PDF, one tender per page, in the layout of sample_rfp_fr.pdf. Empty sections are left out."""
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import cm
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, PageBreak
    body = ParagraphStyle("b", fontName="Helvetica", fontSize=10.5, leading=14.4)
    recs, story = _records(df), []
    if not recs:
        story.append(Paragraph("Aucun appel d'offres collecte lors de cette execution.", body))
    for i, r in enumerate(recs):
        if i:
            story.append(PageBreak())
        story += [Paragraph(_ascii(_header_line(r)), body), Spacer(1, 14.4)]
        for label, value in [("Client:", r.get("acheteur") or r.get("buyer_hint") or "non communique"),
                             ("Secteur:", r.get("type_commande") or "non communique"),
                             ("Date limite de soumission:", _long_date(r.get("date_limite")) or "non communique"),
                             ("Budget previsionnel:", "non communique")]:
            story.append(Paragraph(f"{label} {_ascii(value)}", body))
        secs, presc, keys = r.get("document_sections") or {}, [], []

        def add(v):
            v = re.sub(r"\s+", " ", ARABIC_RE.sub(" ", v or "")).strip()
            if not v:
                return
            k = re.sub(r"\W+", " ", strip_accents(re.sub(r"(?i)\((exige|souhaite)\)", "", v))).strip()
            if k in keys:
                return
            lvl = _req_level(v)
            keys.append(k)
            presc.append(v + (" (Exige)" if lvl == "exige" else " (Souhaite)" if lvl == "souhaite" else "")
                         if not re.search(r"\((exige|souhaite)\)\s*$", strip_accents(v)) else v)

        add(r.get("objet"))
        for v in _sentences(r.get("descriptif")):
            add(v)
        for l in (r.get("lots") or []):
            add(f"Lot {l['lot']} : {l['objet']}" if l.get("objet") else f"Lot {l['lot']}")
            if l.get("region"):
                add(f"Lot {l['lot']} - Region d'execution : {l['region']}")
            if l.get("cautionnement_provisoire"):
                add(f"Lot {l['lot']} - Cautionnement provisoire : {l['cautionnement_provisoire']}")
        for v in _items(secs.get("prescriptions")):
            add(v)
        if presc:
            story += [Spacer(1, 14.4), Paragraph("CAHIER DES PRESCRIPTIONS TECHNIQUES", body), Spacer(1, 14.4)]
            story += [Paragraph(f"{n}. {_ascii(v)}", body) for n, v in enumerate(presc, 1)]
        if secs.get("personnel"):
            story += [Spacer(1, 14.4), Paragraph("EXIGENCES EN PERSONNEL", body), Spacer(1, 14.4)]
            story += [Paragraph(f"- {_ascii(v)}", body) for v in _items(secs["personnel"])]
        if secs.get("references"):
            story += [Spacer(1, 14.4), Paragraph("REFERENCES", body), Spacer(1, 14.4),
                      Paragraph(_ascii(re.sub(r"\s+", " ", secs["references"]).strip()), body)]
        crit = secs.get("criteres") or r.get("methodologie_evaluation")
        if crit:
            story += [Spacer(1, 14.4), Paragraph("CRITERES D'EVALUATION", body), Spacer(1, 14.4)]
            story += [Paragraph(_ascii(re.sub(r"\s+", " ", v)), body)
                      for v in ([x.strip() for x in crit.splitlines() if x.strip()] if "\n" in crit else [crit])]
    SimpleDocTemplate(path, pagesize=A4, leftMargin=2.03 * cm, rightMargin=2.03 * cm, topMargin=2.03 * cm,
                      bottomMargin=2.03 * cm, title="Appels d'offres IT", author="OliveSoft RFP Intelligence").build(story)
    print(f"Saved PDF: {path} ({len(recs)} tenders)")


def quality_report(df, dropped, status, path):
    def count(col):
        return {str(k): int(v) for k, v in df[col].value_counts(dropna=False).items()} if len(df) else {}

    def tally(col):
        out = {}
        for lst in (df[col] if len(df) else []):
            for k in (lst or []):
                out[k] = out.get(k, 0) + 1
        return out
    rep = {"generated_at": datetime.now(TUNIS).isoformat(), "sources": status, "kept": int(len(df)),
           "by_source": count("source_site"), "by_fit": count("olivesoft_fit"), "by_priority": count("priority"),
           "by_segment": count("segment"), "by_detail_level": count("detail_level"),
           "by_notice_kind": count("notice_kind"), "urgent_leads": int(df["urgent"].sum()) if len(df) else 0,
           "missing_fields": tally("missing_fields"), "quality_flags": tally("quality_flags"),
           "dropped": [{"tender_id": r.get("tender_id"), "objet": (r.get("objet") or "")[:120], "reason": why,
                        "segment": r.get("segment")} for r, why in dropped]}
    with open(path, "w", encoding="utf-8") as f:
        json.dump(rep, f, ensure_ascii=False, indent=2)
    print(f"Saved quality report: {path}")
    return rep


def push_webhook(url, records):
    """Send the NEW, medium+ leads to an n8n Webhook node (POST, JSON body {'leads': [...]})."""
    leads = [r for r in records if r.get("is_new") and r.get("fit_rank", 0) >= 2]
    if not leads:
        print("[webhook] no new medium/high lead to send")
        return
    try:
        resp = requests.post(url, json={"count": len(leads), "leads": leads}, timeout=30)
        print(f"[webhook] sent {len(leads)} lead(s) -> HTTP {resp.status_code}")
    except requests.RequestException as e:
        print(f"[webhook] failed (outputs are already saved): {e}")


def _prev_urls(path):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return {r.get("url"): r.get("first_seen_at") for r in json.load(f) if isinstance(r, dict)}
    except (OSError, json.JSONDecodeError, TypeError):
        return {}


