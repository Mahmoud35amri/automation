    r["documents"] = [d for d in (r.get("documents") or []) if "cosem" not in (d.get("label") or "").lower()]
    lots_txt = cut_footer(r.get("lots_text") or "")
    r["lots_text"], r["lots"] = lots_txt or None, parse_lots(lots_txt)
    obj = r.get("objet") or ""
    if ARABIC_RE.search(obj):                           # Arabic-only title -> French descriptif as title
        r["objet_ar"] = obj
        fr = (r.get("descriptif") or "").strip()
        if fr and not ARABIC_RE.search(fr):
            r["objet"] = fr
        else:
            flags.append("title_arabic_only")
    kind, ref, ref_missing = parse_reference(r)
    r["notice_kind"], r["numero_ao"] = kind, ref
    is_ao = "appeloffres" in (r.get("source_site") or "")
    r["missing_fields"] = [k for k in KEY_FIELDS if not r.get(k)]
    if ref_missing:
        flags.append("reference_missing")
        if is_ao and "numero_ao" not in r["missing_fields"]:
            r["missing_fields"].append("numero_ao")
    dl, known = deadline_dt(r)
    r["deadline_time_known"], r["deadline_at"] = known, dl.isoformat() if dl else None
    r["expired"] = bool(dl and dl < now)
    r["days_left"] = (dl.date() - now.date()).days if dl else None
    r["urgent"] = bool(dl and not r["expired"] and r["days_left"] <= 7)
    if "it_score" not in r:
        r["it_score"], r["it_terms"] = it_score(" ".join([r.get("objet") or "", r.get("descriptif") or "", lots_txt]))
    if not r.get("skills_detected"):
        r["skills_detected"] = extract_skills(" ".join([r.get("objet") or "", r.get("descriptif") or "", lots_txt,
                                                        r.get("doc_excerpt") or ""]))
    r["segment"], r["segments"], r["olivesoft_fit"] = classify(r, lots_txt)
    r["fit_rank"] = FIT_RANK[r["olivesoft_fit"]]
    r["buyer_hint"] = None if r.get("acheteur") else buyer_hint(r)
    r["completeness"] = completeness(r)
    r["detail_level"] = "full" if r["completeness"] >= 60 else "listing_only"
    r["requirements"] = extract_requirements(r)
    if not r.get("acheteur"):
        flags.append("buyer_unknown")
    if r.get("titre_tronque"):
        flags.append("title_truncated")
    if not known:
        flags.append("deadline_time_unknown")
    if kind == "report":
        flags.append("postponement_notice")
    if not (r.get("descriptif") or r["lots"] or r.get("doc_excerpt") or r.get("document_sections")):
        flags.append("no_requirements_text")
    if r["expired"]:
        flags.append("expired")
    if not r.get("date_limite"):
        flags.append("deadline_missing")
    r["quality_flags"] = flags
    r["lead_score"] = lead_score(r)
    r["priority"] = "hot" if r["lead_score"] >= 70 else "warm" if r["lead_score"] >= 45 else "cold"
    r["rag_query"] = build_rag_query(r)
    r["is_new"] = r["url"] not in prev
    r["first_seen_at"] = prev.get(r["url"]) or now.isoformat()
    return r


