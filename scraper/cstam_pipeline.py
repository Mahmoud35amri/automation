def run(a):
    os.makedirs(a.out_dir, exist_ok=True)
    P = {k: os.path.join(a.out_dir, f"{a.prefix}_{v}") for k, v in
         dict(json="combined.json", csv="combined.csv", pdf="report.pdf", qual="quality_report.json").items()}
    debug_path = os.path.join(a.out_dir, "listing_debug.html")
    prev, now, status = _prev_urls(P["json"]), datetime.now(TUNIS), {}
    kw = [k for k in a.keywords.split(",") if k.strip()]
    it_only, hc_rows, ao_rows = not a.all, [], []
    sources = [s.strip() for s in a.sources.split(",") if s.strip()]

    if a.demo:
        hc_rows = demo_rows(now)
        status["demo"] = f"{len(hc_rows)} simulated tenders"
    else:
        if "haicop" in sources:
            try:
                hc_rows = scrape_haicop(
                    a.hc_pages, a.max_tenders, it_only and not a.enrich,
                    a.min_score if a.min_score is not None else HC_MIN_SCORE, kw,
                    [x for x in re.split(r"[,\s]+", a.ids) if x], not a.headed, debug_path)
                status["haicop"] = f"{len(hc_rows)} tenders"
            except Exception as e:
                status["haicop"] = f"FAILED: {e}"
                traceback.print_exc()
        if "appeloffres" in sources:
            try:
                if a.browser_ua:
                    _session.headers["User-Agent"] = BROWSER_UA
                ao_rows = scrape_ao(a.pages, a.country.lower(), it_only,
                                    a.min_score if a.min_score is not None else AO_MIN_SCORE, kw, debug_path)
                status["appeloffres"] = f"{len(ao_rows)} tenders"
            except Exception as e:
                status["appeloffres"] = f"FAILED: {e}"
                traceback.print_exc()
    print("\n[sources]", status)

    cleaned = [clean_row(r, now, prev) for r in link_portals(hc_rows, ao_rows)]
    kept, dropped = filter_rows(cleaned, a.keep_expired, a.min_fit if it_only else "none")
    print(f"[filter] {len(kept)} kept | dropped {len(dropped)} "
          f"({sum(w == 'expired' for _, w in dropped)} expired, {sum(w != 'expired' for _, w in dropped)} below fit '{a.min_fit}')")
    for r, why in dropped[:40]:
        print(f"   - [{why}] {r.get('tender_id')} | {(r.get('objet') or '')[:90]}")

    df = to_frame(kept)
    if df.empty:
        print("[run] Nothing collected. NO mock data is used (use --demo for a labelled simulated feed). See the log above.")
    export_json(df, P["json"])                          # JSON first: the RAG must always find a valid file
    export_csv(df, P["csv"])
    try:
        export_pdf(df, P["pdf"])
    except Exception as e:
        print(f"  [warn] PDF export failed (JSON/CSV already written): {e}")
    rep = quality_report(df, dropped, status, P["qual"])
    print("[summary] fit:", rep["by_fit"], "| priority:", rep["by_priority"], "| urgent:", rep["urgent_leads"])
    if len(df):
        print(df[["lead_score", "priority", "numero_ao", "acheteur", "objet", "date_limite", "days_left"]]
              .head(10).to_string(index=False, max_colwidth=45))
    if a.webhook:
        push_webhook(a.webhook, _records(df))
    return df


